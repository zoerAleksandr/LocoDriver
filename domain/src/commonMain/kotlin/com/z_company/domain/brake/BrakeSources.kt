/**
 * Ссылки на источник норм. Везде в UI и спеках пункт/таблица указываются вместе с названием документа.
 *
 * Источник - «Правила технического обслуживания тормозного оборудования и управления тормозами железнодорожного подвижного состава
 * железных дорог» (редакция 2025 г., АО «ВНИИЖТ», взамен Правил, утв. Советом по железнодорожному транспорту государств-участников
 * Содружества, протокол от 6-7 мая 2014 г. № 60; файл «Правила по тормозам (по Корр. № 0)»; в тексте реквизиты утверждения (протокол, дата) не заполнены).
 * Нумерация: основной текст - разд. 1-18 (п. 9.2 - справка ВУ-45, п. 9.3 - полное опробование и плотность, табл. 4 разд. 9.3 - время снижения давления в ГР);
 * Приложение 1 - форма ВУ-45; Приложение 2 - «Нормы обеспечения поездов тормозами и допускаемые скорости» (п. 1-7, табл. 1-4, нумерация таблиц своя);
 * Приложение 3 - акт контрольной проверки; Приложение 4 - тормозные пути.
 * Порядок заполнения справки (графы, округление требуемого нажатия вверх) - «Инструкция по техническому обслуживанию вагонов в эксплуатации
 * (инструкция осмотрщику вагонов)» № 808-2022 ПКБ ЦВ, приложение М (принята СЖТ, протокол от 8.12.2022 № 77, введена с 01.07.2023).
 * Прежние Правила 2014 г. (нумерация III.1-III.4, IV.1, п. 25-59) и Инструкция ЦТ-ЦВ-ЦЛ-ВНИИЖТ/277 не применяются. Сверка - docs/VU45_INSTRUCTION_ACTUALITY.md.
 */
object InstructionRef {
    /** Полное название документа с реквизитами. */
    const val FULL = "Правила технического обслуживания тормозного оборудования и управления тормозами железнодорожного подвижного состава железных дорог " +
        "(редакция 2025 г., АО «ВНИИЖТ», взамен Правил, утв. СЖТ, протокол № 60 от 6-7.05.2014)"
    const val SHORT = "Правила ТО тормозного оборудования"
    /** Документ формы ВУ-45 (образец формы). */
    const val FORM_DOC = "Правила ТО тормозного оборудования, прил. 1"
    const val GENITIVE = "Правил ТО тормозного оборудования"
    const val FORM = FORM_DOC
    /** Порядок заполнения справки (графы и особенности). */
    const val FILL_DOC = "Инструкция 808-2022 ПКБ ЦВ, прил. М"

    /** «п. 4.4 прил. 2 Правил ТО тормозного оборудования» (Приложение 2 - нормы обеспечения поездов тормозами). */
    fun p(clause: String) = "п. $clause прил. 2 $GENITIVE"

    /** «табл. 1 прил. 2 Правил ТО тормозного оборудования» (таблицы 1-4 приложения 2). */
    fun table(num: String, appendix: String? = "прил. 2") = "табл. $num" + (appendix?.let { " $it" } ?: "") + " $GENITIVE"

    /** Пункт основного текста: «п. 9.3.3 Правил ТО тормозного оборудования». */
    fun main(clause: String) = "п. $clause $GENITIVE"

    /** Таблица времени снижения давления в ГР (плотность): в основном тексте, не путать с табл. 4 прил. 2 (ручные тормоза). */
    const val DENSITY_TABLE_SHORT = "табл. 4 п. 9.3.3"
    val DENSITY_TABLE = "$DENSITY_TABLE_SHORT $GENITIVE"

    private val refRegex = Regex("""(?:п\.|табл\.) ?(?:\d+|[IVX]+)(?:\.\d+)*(?:\s*[-–,]\s*\d+(?:\.\d+)*)*(?: прил\. \d)?""")

    /**
     * Дописывает название документа после ПЕРВОЙ ссылки на пункт/таблицу в строке («п. 4.4» → «п. 4.4 Правил ТО тормозного оборудования»,
     * «п. 4.4 прил. 2» → «п. 4.4 прил. 2 Правил ТО тормозного оборудования»). Приложение в ссылке пишется явно: по самому номеру оно
     * не определяется (основной текст и приложение 2 нумеруются независимо). Строка, уже называющая документ (или 808-2022), не меняется.
     */
    fun annotate(text: String): String {
        if (text.contains("Правил") || text.contains("808-2022") || text.contains("Инструкци")) return text
        val m = refRegex.find(text) ?: return text
        return text.substring(0, m.range.last + 1) + " $GENITIVE" + text.substring(m.range.last + 1)
    }
}
