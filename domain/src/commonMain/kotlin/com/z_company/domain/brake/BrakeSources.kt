package com.z_company.domain.brake

/**
 * Ссылки на источник норм. Везде в UI и спеках пункт/таблица указываются вместе с названием документа.
 *
 * Источник - «Правила технического обслуживания тормозного оборудования и управления тормозами железнодорожного подвижного состава»
 * (утв. Советом по железнодорожному транспорту государств-участников Содружества, протокол от 6-7 мая 2014 г. № 60; с изменениями
 * 2015-2017). Нормы - Приложение 2 (разд. III «Нормы обеспечения поездов тормозами», разд. IV «Порядок проведения опробования»).
 * Форма ВУ-45 - Инструкция по техническому обслуживанию вагонов в эксплуатации № 808-2017 ПКБ ЦВ, прил. К.
 * Прежняя Инструкция ЦТ-ЦВ-ЦЛ-ВНИИЖТ/277 (МПС, 1994) не действует. Таблица соответствий - docs/VU45_INSTRUCTION_ACTUALITY.md.
 */
object InstructionRef {
    /** Полное название документа с реквизитами. */
    const val FULL = "Правила технического обслуживания тормозного оборудования и управления тормозами железнодорожного подвижного состава " +
        "(СЖТ государств-участников Содружества, протокол № 60 от 6-7.05.2014, с изменениями до 2017 г.)"
    const val SHORT = "Правила ТО тормозного оборудования"
    const val GENITIVE = "Правил ТО тормозного оборудования"
    const val FORM = "Инструкция 808-2017 ПКБ ЦВ, прил. К"

    /** «п. 35 прил. 2 Правил ТО тормозного оборудования» (Приложение 2 - нормы обеспечения поездов тормозами и опробование). */
    fun p(clause: String) = "п. $clause прил. 2 $GENITIVE"

    /** «табл. III.1 прил. 2 Правил ТО тормозного оборудования» */
    fun table(num: String, appendix: String? = "прил. 2") = "табл. $num" + (appendix?.let { " $it" } ?: "") + " $GENITIVE"

    /** Пункт основного текста: «п. 133 Правил ТО тормозного оборудования». */
    fun main(clause: String) = "п. $clause $GENITIVE"

    private val refRegex = Regex("""(?:п\.|табл\.) ?(?:\d+|[IVX]+)(?:\.\d+)*(?:\s*[-–,]\s*\d+(?:\.\d+)*)*""")

    private fun isAppendix2(ref: String): Boolean {
        if (ref.startsWith("табл. III") || ref.startsWith("табл. IV")) return true
        val n = Regex("""\d+""").find(ref)?.value?.toIntOrNull() ?: return false
        return n in 25..59
    }

    /**
     * Дописывает название документа после ПЕРВОЙ ссылки на пункт/таблицу в строке («п. 35» → «п. 35 прил. 2 Правил ТО тормозного оборудования»).
     * Строка, уже называющая документ (или 808-2017), не меняется.
     */
    fun annotate(text: String): String {
        if (text.contains("Правил") || text.contains("808-2017") || text.contains("Инструкци")) return text
        val m = refRegex.find(text) ?: return text
        val appendix = if (isAppendix2(m.value)) " прил. 2" else ""
        return text.substring(0, m.range.last + 1) + "$appendix $GENITIVE" + text.substring(m.range.last + 1)
    }
}
