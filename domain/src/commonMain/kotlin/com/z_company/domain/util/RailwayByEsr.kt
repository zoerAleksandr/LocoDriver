package com.z_company.domain.util

/**
 * Железная дорога станции (SCREEN_SPECS §6.6): по тегу operator из карты, иначе по коду ЕСР.
 *
 * Первые цифры кода ЕСР - номер сетевого района, дорога обычно занимает несколько подряд идущих районов. Таблица диапазонов
 * выведена из выгрузки osm.sbin.ru/esr (≈25,7 тыс. станций с дорогой; октябрь 2026): диапазоны россий­ских дорог в ней чистые,
 * кроме нескольких «вкраплений» на стыках (Ю-В/Ск-Кав, Приволжская, Крымская, Якутия) - они заданы отдельными диапазонами. Сахалин (99xxxx) отдан Дальневосточной: Сахалинская дорога - её подразделение; границы БАМ/Нерюнгри/Приволжской на
 * стыках уточнены по подтверждению пользователя.
 * Станции СНГ/Балтии и коды вне диапазонов дают null: лучше не показывать дорогу, чем показать неверную.
 * Чистая функция по константной таблице (бинарный поиск) - без ввода-вывода, безопасна на главном потоке.
 */
object RailwayByEsr {
    private const val YAKUTIA = "Железные дороги Якутии"

    // from, to (включительно), дорога - по возрастанию, без пересечений. Одиночные коды - станции, подтверждённые вручную
    // (084059 - Ивангород САИПС, Октябрьская).
    private val FROM = intArrayOf(
        10000, 84059, 100001, 104202, 104708, 170000, 240000, 259186, 259187, 280000, 434000, 510000, 541109, 541110, 541476,
        541800, 580000, 580511, 586160, 589752, 608464, 630000, 760000, 800000, 830000, 856107, 859017, 867008, 869615, 880000,
        900000, 904576, 905700, 908000, 911624, 911709, 912000, 912204, 913507, 914210, 920000, 940000, 960000,
    )
    private val TO = intArrayOf(
        79999, 84059, 104106, 104407, 105005, 239999, 259185, 259186, 279999, 319999, 439999, 541108, 541109, 541475, 541799,
        544999, 580510, 586159, 589751, 608463, 629999, 659999, 799999, 829999, 856106, 859016, 867007, 869614, 879999, 899999,
        904575, 905699, 907999, 911623, 911708, 911999, 912203, 913506, 914209, 919999, 939999, 959999, 999999,
    )
    private val NAME = arrayOf(
        "Октябрьская", "Октябрьская", "Калининградская", "Калининградская", "Калининградская", "Московская", "Горьковская",
        "Приволжская", "Горьковская", "Северная", "Юго-Восточная", "Северо-Кавказская", "Приволжская", "Северо-Кавказская",
        "Приволжская", "Северо-Кавказская", "Северо-Кавказская", "Юго-Восточная", "Северо-Кавказская", "Юго-Восточная",
        "Приволжская", "Куйбышевская", "Свердловская", "Южно-Уральская", "Западно-Сибирская", "Крымская", "Западно-Сибирская",
        "Крымская", "Западно-Сибирская", "Красноярская", "Восточно-Сибирская", "Дальневосточная", "Восточно-Сибирская",
        "Дальневосточная", "Железные дороги Якутии", "Дальневосточная", "Железные дороги Якутии", "Дальневосточная",
        "Железные дороги Якутии", "Дальневосточная", "Восточно-Сибирская", "Забайкальская", "Дальневосточная",
    )

    /** Названия дорог для разбора operator: длинные раньше коротких. */
    private val OPERATOR_NAMES = NAME.distinct().filter { it != YAKUTIA }.sortedByDescending { it.length }

    /** Дорога по коду ЕСР (6 цифр); null - код не распознан или вне российских диапазонов. */
    fun byEsr(esr: String?): String? {
        val code = esr?.trim()?.takeIf { it.length == 6 && it.all(Char::isDigit) }?.toIntOrNull() ?: return null
        var lo = 0
        var hi = FROM.size - 1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            when {
                code < FROM[mid] -> hi = mid - 1
                code > TO[mid] -> lo = mid + 1
                else -> return NAME[mid]
            }
        }
        return null
    }

    /** Дорога из тега operator («Октябрьская железная дорога», «Южно-Уральская ЖД»); «РЖД» без названия дороги - null. */
    fun byOperator(operator: String?): String? {
        val text = operator?.lowercase()?.takeIf { it.isNotBlank() } ?: return null
        if (YAKUTIA.lowercase() in text) return YAKUTIA
        if ("дорог" !in text && "жд" !in text) return null
        return OPERATOR_NAMES.firstOrNull { it.lowercase() in text }
    }

    /** Подпись для показа («Октябрьская ЖД»): сначала operator, затем код ЕСР; null - дорога неизвестна. */
    fun label(esr: String?, operator: String?): String? {
        val name = byOperator(operator) ?: byEsr(esr) ?: return null
        return if (name == YAKUTIA) name else "$name ЖД"
    }
}
