package com.z_company.domain.util

/**
 * Чувствительность положения на карте поезда (SCREEN_SPECS §6.9, «Настройки карты»). Шкала 1..5, по умолчанию 3 -
 * прежнее поведение. Влияет ТОЛЬКО на то, как маркер на карте реагирует на живые fix'ы (фильтр дрейфа на стоянке и порог
 * «еду»); запись трека («АВТО») и сохранённые данные не меняются.
 *
 * Чем выше чувствительность, тем меньше сглаживания: маркер быстрее реагирует на малые перемещения и медленное движение,
 * но на стоянке и в плохом приёме больше «дрожит».
 */
object LocationSensitivity {
    const val MIN = 1
    const val MAX = 5
    const val DEFAULT = 3

    fun clamp(level: Int): Int = level.coerceIn(MIN, MAX)

    /** Радиус «стоянки», внутри которого дрейф координат гасится (м). */
    fun driftRadiusM(level: Int): Double = when (clamp(level)) {
        1 -> 150.0
        2 -> 120.0
        3 -> 100.0
        4 -> 60.0
        else -> 30.0
    }

    /** Скорость (км/ч), ниже которой считается «стоим»; она же порог «поезд едет» для слежения камеры. */
    fun stillSpeedKmh(level: Int): Double = when (clamp(level)) {
        1 -> 3.0
        2 -> 2.5
        3 -> 2.0
        4 -> 1.5
        else -> 1.0
    }

    /** Параметры фильтра дрейфа для уровня: остальные значения - по умолчанию. */
    fun driftConfig(level: Int): DriftFilter.Config {
        val still = stillSpeedKmh(level)
        return DriftFilter.Config(
            radiusM = driftRadiusM(level),
            stillSpeedKmh = still,
            confirmSpeedKmh = still + 1.0,
            continueSpeedKmh = still,
        )
    }

    fun title(level: Int): String = when (clamp(level)) {
        1 -> "Низкая"
        2 -> "Ниже средней"
        3 -> "Средняя"
        4 -> "Выше средней"
        else -> "Высокая"
    }

    /** Что происходит на этом уровне (для пользователя). */
    fun description(level: Int): String = when (clamp(level)) {
        1 -> "Маркер почти не дрожит: даже заметные колебания GPS на стоянке и в плохом приёме гасятся. " +
            "Но на самом медленном ходу и при трогании с места маркер может отставать."
        2 -> "Маркер стоит спокойно, колебания GPS на стоянке сглажены. На малой скорости может чуть запаздывать."
        3 -> "Рекомендуемый баланс: маркер не дрожит на стоянке и вовремя начинает двигаться."
        4 -> "Маркер быстрее реагирует на трогание и манёвры на малой скорости. На стоянке и в плохом приёме " +
            "он может понемногу «гулять» по карте."
        else -> "Максимальная отзывчивость: видны даже самые малые перемещения и медленный ход. " +
            "Зато на стоянке, в тоннелях, лесу и при плохом приёме маркер заметно дрожит и может прыгать."
    }

    const val GENERAL_NOTE: String =
        "Чем выше чувствительность, тем быстрее маркер реагирует на движение, но тем больше шума от GPS. " +
            "Настройка меняет только отображение положения на карте; запись трека не затрагивается."
}
